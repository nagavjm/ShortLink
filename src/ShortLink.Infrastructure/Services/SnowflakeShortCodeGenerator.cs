using ShortLink.Application.Common.Interfaces;

namespace ShortLink.Infrastructure.Services;

/// <summary>
/// Distributed Snowflake-based short code generator.
/// Generates globally unique 64-bit IDs across multiple API worker instances without database coordination,
/// then Base62 encodes them into unique, non-colliding short codes.
/// </summary>
public class SnowflakeShortCodeGenerator : IShortCodeGenerator
{
    private readonly ISnowflakeIdGenerator _snowflakeIdGenerator;
    private readonly IBase62Service _base62Service;

    public SnowflakeShortCodeGenerator(
        ISnowflakeIdGenerator snowflakeIdGenerator,
        IBase62Service base62Service)
    {
        _snowflakeIdGenerator = snowflakeIdGenerator;
        _base62Service = base62Service;
    }

    public string StrategyName => "Distributed-Snowflake-Base62";

    public string Generate(long entityId)
    {
        // When Snowflake is active, if entityId is already generated by Snowflake, encode it;
        // otherwise generate next distributed ID.
        var id = entityId > 0 ? entityId : _snowflakeIdGenerator.NextId();
        return _base62Service.Encode(id);
    }
}
